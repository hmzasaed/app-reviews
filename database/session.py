"""Engine/session helpers. Works with Supabase Postgres and with SQLite for local dev/tests."""

from collections.abc import Iterator
from contextlib import contextmanager
from functools import lru_cache

from sqlalchemy import create_engine, event, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.engine import Engine
from sqlalchemy.orm import Session, sessionmaker
from sqlalchemy.schema import CreateIndex, CreateTable

from database.models import Base
from pipeline.config import get_settings


def normalize_database_url(url: str) -> str:
    """Accept the plain ``postgresql://`` string Supabase shows and pick the psycopg 3 driver."""
    for prefix in ("postgres://", "postgresql://"):
        if url.startswith(prefix):
            return "postgresql+psycopg://" + url[len(prefix):]
    return url


def make_engine(url: str) -> Engine:
    url = normalize_database_url(url)
    if url.startswith("sqlite"):
        engine = create_engine(url, connect_args={"check_same_thread": False})

        @event.listens_for(engine, "connect")
        def _enable_fk(dbapi_conn, _):  # SQLite ignores foreign keys unless asked
            dbapi_conn.execute("PRAGMA foreign_keys=ON")

        return engine
    # Supabase's transaction pooler (port 6543) does not support prepared statements.
    connect_args = {"prepare_threshold": None} if ":6543/" in url else {}
    return create_engine(url, pool_pre_ping=True, pool_size=5, max_overflow=5, connect_args=connect_args)


@lru_cache
def get_engine() -> Engine:
    return make_engine(get_settings().database_url)


@lru_cache
def get_sessionmaker() -> sessionmaker[Session]:
    return sessionmaker(bind=get_engine(), expire_on_commit=False)


@contextmanager
def session_scope() -> Iterator[Session]:
    session = get_sessionmaker()()
    try:
        yield session
        session.commit()
    except Exception:
        session.rollback()
        raise
    finally:
        session.close()


def postgres_ddl() -> str:
    """The schema as Postgres DDL, for running in the Supabase SQL editor instead of ``init-db``."""
    dialect = postgresql.dialect()
    statements = [
        "-- Generated by `python -m pipeline.cli schema-sql` from database/models.py. Do not edit by hand.\n"
        "-- Paste into the Supabase SQL editor, or run `python -m pipeline.cli init-db` instead.\n"
        "-- RLS is enabled with no policies: the API connects as the table owner, while Supabase's\n"
        "-- public REST API (anon key) gets no access to these tables."
    ]
    for table in Base.metadata.sorted_tables:
        statements.append(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
        statements += [str(CreateIndex(i, if_not_exists=True).compile(dialect=dialect)).strip() + ";" for i in table.indexes]
        statements.append(f'ALTER TABLE "{table.name}" ENABLE ROW LEVEL SECURITY;')
    return "\n\n".join(statements) + "\n"


def init_db(engine: Engine | None = None) -> None:
    """Create tables. On Postgres (Supabase) also enable Row Level Security.

    The API connects as the database owner, which bypasses RLS. Enabling RLS with no
    policies stops Supabase's public REST endpoint (anon key) from exposing the tables.
    """
    engine = engine or get_engine()
    Base.metadata.create_all(engine)
    if engine.dialect.name == "postgresql":
        with engine.begin() as conn:
            for table in Base.metadata.sorted_tables:
                conn.execute(text(f'ALTER TABLE "{table.name}" ENABLE ROW LEVEL SECURITY'))
